export type Locale = "zh" | "en";

/** 翻译函数：locale 为 zh 或字典缺失时返回原文。 */
export function translate(locale: Locale, zh: string): string {
  if (locale === "zh") return zh;
  return en[zh] ?? zh;
}

/** 带模板占位符 {n} 的翻译。 */
export function translateFmt(locale: Locale, zh: string, vars: Record<string, string | number>): string {
  const base = translate(locale, zh);
  return base.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

/** 返回当前 locale 对应的翻译函数：组件内 `const t = useT(); t("打开")`。 */
export function useT(): (zh: string, vars?: Record<string, string | number>) => string {
  const locale = useApp((s) => s.locale);
  return (zh, vars) => (vars ? translateFmt(locale, zh, vars) : translate(locale, zh));
}